import { getThemeCustomCss, normalizeThemeCss } from './sillybunny-theme-css.js';

/**
 * Bundled themes that had their text colors raised to the DESIGN.md contrast floor. Selecting a theme copies its
 * colors and Custom CSS into the user's settings, so a user who selected one before the change keeps the old values
 * until something replaces them. `planThemeTextRepair` decides what to replace, and power-user.js applies it once.
 *
 * Bump THEME_TEXT_REVISION (and the matching constant in power-user.js) when a later revision is added to the data.
 */
export const THEME_TEXT_REVISION = 1;

/** The ten color keys that the saved palette is compared on, in the order of the theme files. */
export const THEME_COLOR_KEYS = Object.freeze([
    'main_text_color',
    'italics_text_color',
    'underline_text_color',
    'quote_text_color',
    'blur_tint_color',
    'chat_tint_color',
    'user_mes_blur_tint_color',
    'bot_mes_blur_tint_color',
    'shadow_color',
    'border_color',
]);

/** The keys a revision changes. Everything else in the saved palette is left as the user has it. */
export const THEME_TEXT_KEYS = Object.freeze(THEME_COLOR_KEYS.slice(0, 4));

/**
 * Hashes Custom CSS to a short string. It is a plain string hash because crypto.subtle is missing on pages served
 * over plain http from another machine, which is how SillyBunny is often reached on a local network.
 * @param {unknown} css Custom CSS.
 * @returns {string} Hash of the normalized CSS.
 */
export function hashThemeCss(css) {
    const text = normalizeThemeCss(css);
    let h1 = 0xdeadbeef;
    let h2 = 0x41c6ce57;
    for (let index = 0; index < text.length; index++) {
        const code = text.charCodeAt(index);
        h1 = Math.imul(h1 ^ code, 2654435761);
        h2 = Math.imul(h2 ^ code, 1597334677);
    }
    h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
    h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
    return (4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(16);
}

/**
 * What to put into a user's saved settings, given what they have saved.
 *
 * The saved palette (all ten color keys) and the theme name must equal an earlier bundled version of the theme;
 * anything else is left alone. When the saved Custom CSS is also that earlier version and the loaded theme list
 * carries the revised CSS, the CSS is replaced as well. Custom CSS the user edited is never replaced: a palette
 * change cannot lose edits, and replacing the CSS could.
 * @param {object} saved What the user has saved.
 * @param {string} saved.themeName Name of the selected theme.
 * @param {Record<string, string>} saved.palette Saved colors, read by THEME_COLOR_KEYS.
 * @param {unknown} saved.customCss Saved Custom CSS.
 * @param {object[]} saved.themes Themes the user has, from the user's themes folder.
 * @returns {{ text: Record<string, string>, css: string|null }|null} The new text colors, and the revised CSS to
 * replace the saved CSS with (null to leave the CSS), or null when nothing matches.
 */
export function planThemeTextRepair({ themeName, palette, customCss, themes }) {
    const revision = Object.hasOwn(REVISED_THEMES, themeName) ? REVISED_THEMES[themeName] : null;
    if (!revision || !THEME_COLOR_KEYS.every(key => palette?.[key] === revision.old[key])) {
        return null;
    }

    const loadedCss = getThemeCustomCss(themes?.find(theme => theme.name === themeName));
    const replacesCss = revision.oldCss !== revision.newCss
        && hashThemeCss(customCss) === revision.oldCss
        && loadedCss !== null
        && hashThemeCss(loadedCss) === revision.newCss;

    return { text: { ...revision.text }, css: replacesCss ? loadedCss : null };
}

