function isPlainObject(value) {
    if (!value || typeof value !== "object" || Array.isArray(value)) return false;
    const prototype = Object.getPrototypeOf(value);
    return prototype === Object.prototype || prototype === null;
}

function byteLength(value) {
    return new TextEncoder().encode(value).byteLength;
}

export function coerceSettingsFieldValue(key, value, options = {}) {
    const bounds = SETTINGS_NUMBER_BOUNDS[key];
    if (bounds) {
        if (value === null && bounds[3]) return null;
        const numeric = typeof value === "number"
            ? value
            : (typeof value === "string" && value.trim() ? Number(value) : NaN);
        if (!Number.isFinite(numeric)) return undefined;
        let [min, max, integer] = bounds;
        if (key === "cfgScale" && options.provider === "proxy") min = 0;
        const bounded = Math.min(max, Math.max(min, numeric));
        return integer ? Math.trunc(bounded) : bounded;
    }

    if (SETTINGS_BOOLEAN_FIELDS.has(key)) {
        if (typeof value === "boolean") return value;
        if (value === 1 || value === "1" || value === "true") return true;
        if (value === 0 || value === "0" || value === "false") return false;
        return undefined;
    }

    if (key === "injectInsertMode" && ["replace", "inline", "new"].includes(value)) {
        return normalizeInjectInsertMode(value);
    }

    const enumValues = SETTINGS_ENUM_VALUES[key];
    if (enumValues) return typeof value === "string" && enumValues.includes(value) ? value : undefined;

    const expectsString = options.defaultType === "string"
        || SETTINGS_STRING_FIELDS.has(key)
        || SETTINGS_STRING_FIELD_SUFFIX.test(key);
    if (expectsString) {
        if (key === "model" && value === null) return null;
        if (typeof value !== "string") return undefined;
    } else if (typeof value !== "string") {
        return value;
    }

    const configuredLimit = Number(options.maxStringBytes);
    const maxStringBytes = Number.isFinite(configuredLimit) && configuredLimit >= 0
        ? configuredLimit
        : MAX_STRING_BYTES;
    return byteLength(value) <= maxStringBytes ? value : undefined;
}

function isPrivateField(key) {
    if (/cardkey$/i.test(key)) return false;
    return key.startsWith("_") || CUSTOM_API_FIELD.test(key) || COMFY_EXECUTABLE_FIELD.test(key) || COMFY_LOCAL_TRUST_FIELD.test(key) || isCredentialFieldName(key) || PRIVATE_FIELD.test(key) || KNOWN_PRIVATE_FIELD.test(key) || DELIMITED_PRIVATE_FIELD.test(key);
}

function isComfyWorkflowPrivateField(key) {
    return isPrivateField(key) || COMFY_WORKFLOW_BODY_FIELD.test(key);
}

function isLocalTrustField(key) {
    return CUSTOM_API_FIELD.test(key) || isPrivateField(key) || TRUSTED_ENDPOINT_FIELD.test(key) || key === "url" || key === "endpoint";
}

function isComfyWorkflowLocalTrustField(key) {
    return isLocalTrustField(key) || COMFY_WORKFLOW_BODY_FIELD.test(key);
}

function isStructuredSettingsField(key) {
    return /workflow/i.test(key) || key === "customApiRequestTemplate";
}

function sanitizeForExport(value, key = "", seen = new WeakSet(), depth = 0, isOmittedField = isPrivateField, state = null) {
    const currentPath = state ? state.path : "";
    const childState = (childPath) => (state ? { omissions: state.omissions, path: childPath } : null);
    const omit = (path, reason) => {
        if (state) state.omissions.push(`${path || "(root)"}: ${reason}`);
        return undefined;
    };

    if (isOmittedField(key) || depth > MAX_DEPTH) {
        return depth > MAX_DEPTH ? omit(currentPath, `nested too deeply (limit ${MAX_DEPTH})`) : undefined;
    }
    if (value == null || typeof value === "boolean") return value;
    if (typeof value === "number") return Number.isFinite(value) ? value : omit(currentPath, "non-finite number");
    if (typeof value === "string") {
        if (/^(?:data:image\/|blob:)/i.test(value)) return undefined;
        if (isStructuredSettingsField(key) && /^\s*[\[{]/.test(value)) {
            try {
                const parsed = JSON.parse(value);
                const sanitized = sanitizeForExport(parsed, key, seen, depth + 1, isOmittedField, childState(currentPath));
                return sanitized === undefined ? undefined : JSON.stringify(sanitized);
            } catch {
                if (/["'](?:api[_-]?key|access[_-]?token|auth|authorization|token|secret|password|passwd)["']\s*:/i.test(value)) {
                    return undefined;
                }
                return omit(currentPath, "invalid structured string");
            }
        }
        if (byteLength(value) > MAX_STRING_BYTES) return omit(currentPath, `string over ${MAX_STRING_BYTES} bytes`);
        return /model$/i.test(key) ? sanitizeReproducibleModel(value) : redactUrlCredentials(value);
    }
    if (typeof value !== "object" || seen.has(value)) {
        return seen.has(value) ? omit(currentPath, "repeated object reference") : omit(currentPath, `unsupported ${typeof value} value`);
    }
    seen.add(value);

    if (Array.isArray(value)) {
        if (value.length > MAX_ARRAY_ITEMS) omit(currentPath, `array truncated from ${value.length} to ${MAX_ARRAY_ITEMS} items`);
        return value.slice(0, MAX_ARRAY_ITEMS)
            .map((item, index) => sanitizeForExport(item, key, seen, depth + 1, isOmittedField, childState(`${currentPath}[${index}]`)))
            .filter((item) => item !== undefined);
    }
    if (!isPlainObject(value)) return omit(currentPath, "non-plain object");

    const entries = Object.entries(value);
    if (entries.length > MAX_OBJECT_KEYS) omit(currentPath, `object truncated from ${entries.length} to ${MAX_OBJECT_KEYS} fields`);
    const result = {};
    for (const [childKey, childValue] of entries.slice(0, MAX_OBJECT_KEYS)) {
        if (FORBIDDEN_KEYS.has(childKey)) continue;
        const childPath = currentPath ? `${currentPath}.${childKey}` : childKey;
        const sanitized = sanitizeForExport(childValue, childKey, seen, depth + 1, isOmittedField, childState(childPath));
        if (sanitized !== undefined) result[childKey] = sanitized;
    }
    if (String(value.provider || "").toLowerCase() === "custom") delete result.model;
    return result;
}

function sanitizeContextMedia(value, key = "", depth = 0) {
    if (depth > MAX_DEPTH) return undefined;
    if (key === "chatMap") return {};
    if (key.toLowerCase() === "media") return Array.isArray(value) ? [] : undefined;
    if (CONTEXT_MEDIA_PRIVATE_FIELD.test(key)) return undefined;
    if (typeof value === "string" && CONTEXT_MEDIA_PRIVATE_STRING.test(value)) return undefined;
    if (Array.isArray(value)) {
        return value.map((item) => sanitizeContextMedia(item, key, depth + 1))
            .filter((item) => item !== undefined);
    }
    if (!isPlainObject(value)) return value;
    const result = {};
    for (const [childKey, childValue] of Object.entries(value)) {
        const sanitized = sanitizeContextMedia(childValue, childKey, depth + 1);
        if (sanitized !== undefined) result[childKey] = sanitized;
    }
    return result;
}

function cloneValidated(value, path, state, depth = 0) {
    if (depth > MAX_DEPTH) throw new Error(`${path} is nested too deeply`);
    state.nodes += 1;
    if (state.nodes > MAX_NODES) throw new Error("Settings file contains too many values");

    if (value == null || typeof value === "boolean" || typeof value === "string") {
        if (typeof value === "string" && byteLength(value) > MAX_STRING_BYTES) {
            throw new Error(`${path} contains an oversized string`);
        }
        return value;
    }
    if (typeof value === "number") {
        if (!Number.isFinite(value)) throw new Error(`${path} contains an invalid number`);
        return value;
    }
    if (Array.isArray(value)) {
        if (value.length > MAX_ARRAY_ITEMS) throw new Error(`${path} contains too many items`);
        return value.map((item, index) => cloneValidated(item, `${path}[${index}]`, state, depth + 1));
    }
    if (!isPlainObject(value)) throw new Error(`${path} must contain JSON values only`);

    const entries = Object.entries(value);
    if (entries.length > MAX_OBJECT_KEYS) throw new Error(`${path} contains too many fields`);
    const result = {};
    for (const [childKey, childValue] of entries) {
        if (FORBIDDEN_KEYS.has(childKey)) throw new Error(`${path} contains forbidden field ${childKey}`);
        result[childKey] = cloneValidated(childValue, `${path}.${childKey}`, state, depth + 1);
    }
    return result;
}

function assertShape(value, shape, name) {
    if (shape === "array" && !Array.isArray(value)) throw new Error(`${name} must be an array`);
    if (shape === "object" && !isPlainObject(value)) throw new Error(`${name} must be an object`);
}

function createDefaultId(prefix) {
    if (globalThis.crypto?.randomUUID) return globalThis.crypto.randomUUID();
    return `${prefix}_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 10)}`;
}

function normalizeRecordIds(records, name, createId) {
    if (!Array.isArray(records)) return;
    const seen = new Set();
    for (const record of records) {
        if (!isPlainObject(record)) throw new Error(`${name} entries must be objects`);
        let id = typeof record.id === "string" ? record.id.trim() : "";
        if (!id) id = createId(name);
        if (!SAFE_ID.test(id)) throw new Error(`${name} contains an invalid ID`);
        if (seen.has(id)) throw new Error(`${name} contains duplicate ID ${id}`);
        seen.add(id);
        record.id = id;
    }
}

function validateIdList(value, path) {
    if (!Array.isArray(value)) throw new Error(`${path} must be an array`);
    const seen = new Set();
    for (const idValue of value) {
        const id = typeof idValue === "string" ? idValue.trim() : "";
        if (!SAFE_ID.test(id)) throw new Error(`${path} contains an invalid ID`);
        if (seen.has(id)) throw new Error(`${path} contains duplicate ID ${id}`);
        seen.add(id);
    }
}

function validateIdMap(value, path) {
    if (!isPlainObject(value)) throw new Error(`${path} must be an object`);
    for (const [scope, ids] of Object.entries(value)) validateIdList(ids, `${path}.${scope}`);
}

function removeImportedPrivateFields(value, key = "", depth = 0, isOmittedField = isLocalTrustField) {
    if (isOmittedField(key) || depth > MAX_DEPTH) return undefined;
    if (typeof value === "string" && /^(?:data:image\/|blob:)/i.test(value)) return undefined;
    if (typeof value === "string" && /model$/i.test(key)) return sanitizeReproducibleModel(value);
    if (typeof value === "string" && isStructuredSettingsField(key) && /^\s*[\[{]/.test(value)) {
        try {
            const parsed = JSON.parse(value);
            const sanitized = removeImportedPrivateFields(parsed, key, depth + 1, isOmittedField);
            return sanitized === undefined ? undefined : JSON.stringify(sanitized);
        } catch {
            return undefined;
        }
    }
    if (Array.isArray(value)) {
        return value.map((item) => removeImportedPrivateFields(item, key, depth + 1, isOmittedField))
            .filter((item) => item !== undefined);
    }
    if (!isPlainObject(value)) return value;
    const result = {};
    for (const [childKey, childValue] of Object.entries(value)) {
        if (childKey === "provider" && String(childValue).toLowerCase() === "custom") continue;
        const sanitized = removeImportedPrivateFields(childValue, childKey, depth + 1, isOmittedField);
        if (sanitized !== undefined) result[childKey] = sanitized;
    }
    if (String(value.provider || "").toLowerCase() === "custom") delete result.model;
    return result;
}

function normalizeImportedSettingsValues(value, key = "", depth = 0, provider = "") {
    if (depth > MAX_DEPTH) return undefined;
    const normalized = coerceSettingsFieldValue(key, value, { maxStringBytes: MAX_STRING_BYTES, provider });
    if (normalized === undefined || normalized === null || typeof normalized !== "object") return normalized;
    if (Array.isArray(normalized)) {
        return normalized.map((item) => normalizeImportedSettingsValues(item, key, depth + 1, provider))
            .filter((item) => item !== undefined);
    }
    if (!isPlainObject(normalized)) return undefined;
    const recordProvider = typeof normalized.provider === "string" ? normalized.provider : provider;
    const result = {};
    for (const [childKey, childValue] of Object.entries(normalized)) {
        const child = normalizeImportedSettingsValues(childValue, childKey, depth + 1, recordProvider);
        if (child !== undefined) result[childKey] = child;
    }
    return result;
}

export function createSettingsExport(source, options = {}) {
    const omissions = [];
    const state = { omissions, path: "" };
    const payload = {
        version: SETTINGS_TRANSFER_VERSION,
        exportDate: (options.now || new Date()).toISOString(),
        privacy: {
            secrets: "omitted",
            privateImages: "omitted",
        },
        activeSettings: sanitizeForExport(source?.activeSettings || {}, "", new WeakSet(), 0, isPrivateField, state) || {},
    };
    for (const name of EXPORTED_STORE_NAMES) {
        let store = source?.[name];
        if (name === "connectionProfiles" && isPlainObject(store)) {
            store = Object.fromEntries(Object.entries(store).filter(([provider]) => provider !== "custom"));
        } else if (name === "generationPresets" && Array.isArray(store)) {
            store = store.filter(record => record?.provider !== "custom");
        }
        let sanitized = sanitizeForExport(
            store,
            "",
            new WeakSet(),
            0,
            name === "comfyWorkflows" ? isComfyWorkflowPrivateField : isPrivateField,
            { omissions, path: name },
        );
        if (name === "contextMedia" && sanitized !== undefined) sanitized = sanitizeContextMedia(sanitized);
        if (sanitized !== undefined) payload[name] = sanitized;
    }
    if (omissions.length && typeof options.onOmission === "function") {
        options.onOmission(omissions.slice());
    }
    return payload;
}

export function parseSettingsImport(text, options = {}) {
    if (typeof text !== "string" || byteLength(text) > MAX_SETTINGS_IMPORT_BYTES) {
        throw new Error(`Settings files must be smaller than ${MAX_SETTINGS_IMPORT_BYTES / (1024 * 1024)} MiB`);
    }

    let parsed;
    try {
        parsed = JSON.parse(text);
    } catch {
        throw new Error("Settings file is not valid JSON");
    }
    if (!isPlainObject(parsed)) throw new Error("Settings file must contain an object");
    const version = Number(parsed.version);
    if (!Number.isInteger(version) || version < 5 || version > SETTINGS_TRANSFER_VERSION) {
        throw new Error(`Unsupported settings version: ${parsed.version ?? "missing"}`);
    }

    const result = {
        version: SETTINGS_TRANSFER_VERSION,
        sourceVersion: version,
        exportDate: typeof parsed.exportDate === "string" ? parsed.exportDate : null,
    };
    const state = { nodes: 0 };
    const createId = options.createId || createDefaultId;

    if (parsed.activeSettings !== undefined) {
        assertShape(parsed.activeSettings, "object", "activeSettings");
        const cloned = cloneValidated(parsed.activeSettings, "activeSettings", state);
        const normalized = normalizeImportedSettingsValues(removeImportedPrivateFields(cloned)) || {};
        if (normalized.reviewBeforeGenerate === undefined && normalized.llmEditPrompt !== undefined) {
            normalized.reviewBeforeGenerate = Boolean(normalized.llmEditPrompt);
        }
        delete normalized.llmEditPrompt;
        result.activeSettings = normalized;
    }

    for (const [name, shape] of Object.entries(STORE_SHAPES)) {
        if (parsed[name] === undefined) continue;
        if (name === "charRefImages" && version >= 6) continue;
        if (name === "comfyWorkflows") continue;
        assertShape(parsed[name], shape, name);
        let cloned = cloneValidated(parsed[name], name, state);
        if (name === "connectionProfiles" && isPlainObject(cloned)) delete cloned.custom;
        if (name === "generationPresets" && Array.isArray(cloned)) {
            cloned = cloned.filter(record => record?.provider !== "custom");
        }
        const portable = name === "charRefImages"
            ? cloned
            : removeImportedPrivateFields(
                cloned,
                "",
                0,
                name === "comfyWorkflows" ? isComfyWorkflowLocalTrustField : isLocalTrustField,
            );
        result[name] = normalizeImportedSettingsValues(portable) ?? (shape === "array" ? [] : {});
        if (name === "contextMedia") result[name] = sanitizeContextMedia(result[name]) || {};
    }

    normalizeRecordIds(result.comfyWorkflows, "comfyWorkflows", createId);
    normalizeRecordIds(result.generationPresets, "generationPresets", createId);
    normalizeRecordIds(result.contextualFilters, "contextualFilters", createId);
    normalizeRecordIds(result.filterPools, "filterPools", createId);
    if (result.activeFilterPoolIdsGlobal) validateIdList(result.activeFilterPoolIdsGlobal, "activeFilterPoolIdsGlobal");
    if (result.activeFilterPoolIdsByCard) validateIdMap(result.activeFilterPoolIdsByCard, "activeFilterPoolIdsByCard");
    if (result.activeFilterPoolIdsByChar) validateIdMap(result.activeFilterPoolIdsByChar, "activeFilterPoolIdsByChar");
    for (const [index, filter] of (result.contextualFilters || []).entries()) {
        if (filter.poolIds !== undefined) validateIdList(filter.poolIds, `contextualFilters[${index}].poolIds`);
    }
    return result;
}

export function mergePreservingPrivateFields(current, imported, key = "") {
    if (isLocalTrustField(key)) return current;
    if (Array.isArray(imported)) return imported.map((item) => mergePreservingPrivateFields(undefined, item, key));
    if (!isPlainObject(imported)) return imported;

    const result = {};
    for (const [childKey, childValue] of Object.entries(imported)) {
        result[childKey] = mergePreservingPrivateFields(current?.[childKey], childValue, childKey);
    }
    if (isPlainObject(current)) {
        for (const [childKey, childValue] of Object.entries(current)) {
            if (isLocalTrustField(childKey) && result[childKey] === undefined) result[childKey] = childValue;
        }
    }
    return result;
}

function cloneLocalRecord(value) {
    if (value === undefined) return undefined;
    if (typeof structuredClone === "function") return structuredClone(value);
    return JSON.parse(JSON.stringify(value));
}

export function mergeSettingsImportStores(current = {}, imported = {}) {
    const result = {};
    if (imported.connectionProfiles !== undefined) {
        const portableProfiles = isPlainObject(imported.connectionProfiles)
            ? Object.fromEntries(Object.entries(imported.connectionProfiles).filter(([provider]) => provider !== "custom"))
            : {};
        const mergedProfiles = {};
        for (const [provider, importedRecords] of Object.entries(portableProfiles)) {
            const currentRecords = isPlainObject(current.connectionProfiles?.[provider]) ? current.connectionProfiles[provider] : {};
            const merged = mergePreservingPrivateFields(currentRecords, importedRecords);
            for (const [name, record] of Object.entries(currentRecords)) {
                if (!Object.prototype.hasOwnProperty.call(importedRecords, name)) merged[name] = cloneLocalRecord(record);
            }
            mergedProfiles[provider] = merged;
        }
        if (isPlainObject(current.connectionProfiles)) {
            for (const [provider, records] of Object.entries(current.connectionProfiles)) {
                if (provider === "custom" || portableProfiles[provider] !== undefined) continue;
                mergedProfiles[provider] = cloneLocalRecord(records);
            }
            if (Object.prototype.hasOwnProperty.call(current.connectionProfiles, "custom")) {
                mergedProfiles.custom = cloneLocalRecord(current.connectionProfiles.custom);
            }
        }
        result.connectionProfiles = mergedProfiles;
    }
    if (imported.generationPresets !== undefined) {
        const localPortable = Array.isArray(current.generationPresets)
            ? current.generationPresets.filter(record => record?.provider !== "custom").map(cloneLocalRecord)
            : [];
        const importedPortable = Array.isArray(imported.generationPresets)
            ? imported.generationPresets.filter(record => record?.provider !== "custom").map(cloneLocalRecord)
            : [];
        const importedIds = new Set(importedPortable.map(record => record?.id).filter(id => typeof id === "string" && id));
        const retainedLocal = localPortable.filter(record => !(typeof record?.id === "string" && importedIds.has(record.id)));
        const localCustom = Array.isArray(current.generationPresets)
            ? current.generationPresets.filter(record => record?.provider === "custom").map(cloneLocalRecord)
            : [];
        result.generationPresets = [...importedPortable, ...retainedLocal, ...localCustom];
    }
    return result;
}

export function stageStorageTransaction(storage, updates) {
    const entries = updates instanceof Map ? [...updates.entries()] : Object.entries(updates || {});
    const previous = new Map(entries.map(([key]) => [key, storage.getItem(key)]));
    let active = true;

    const restore = () => {
        if (!active) return;
        const errors = [];
        for (const [key, value] of previous.entries()) {
            try {
                if (value == null) storage.removeItem(key);
                else storage.setItem(key, value);
            } catch (error) {
                errors.push(error);
                try {
                    storage.removeItem(key);
                } catch (removeError) {
                    errors.push(removeError);
                }
            }
        }
        active = false;
        if (errors.length) throw new AggregateError(errors, "Settings storage could not be fully rolled back");
    };

    try {
        for (const [key, value] of entries) storage.setItem(key, value);
    } catch (error) {
        try {
            restore();
        } catch (rollbackError) {
            throw new AggregateError([error, rollbackError], "Settings storage failed and could not be fully rolled back");
        }
        throw new Error("Could not save imported settings. Browser storage may be full.", { cause: error });
    }

    return {
        commit() { active = false; },
        rollback: restore,
    };
}
