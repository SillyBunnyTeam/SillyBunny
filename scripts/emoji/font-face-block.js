/**
 * The `@font-face` block that `build-emoji-font.js` writes into `public/css/sillybunny-conversation.css` between two
 * marker comments, and that `tests/sillybunny-conversation-emoji-font-css.test.js` reads back. One function renders it, so
 * the script and the test cannot disagree about what the block is.
 */

export const BLOCK_BEGIN = '/* BEGIN generated by scripts/emoji/build-emoji-font.js from scripts/emoji/font-unicode-range.txt. Do not edit by hand. */';
export const BLOCK_END = '/* END generated */';

/**
 * @param {{ family: string, file: string, cacheKey: string, range: string }} parts
 */
export function renderFontFaceBlock({ family, file, cacheKey, range }) {
    return [
        BLOCK_BEGIN,
        '/* Twemoji graphics (CC BY 4.0, see ../webfonts/SBEmoji/LICENSE-GRAPHICS), converted into a COLRv0 font. The range is the font\'s own characters',
        '   without the ones that text uses (the space, digits, # and *, the copyright, registered and trade mark signs). */',
        '@font-face {',
        `    font-family: '${family}';`,
        '    font-style: normal;',
        '    font-weight: 400;',
        '    font-display: swap;',
        `    src: url('../webfonts/SBEmoji/${file}?v=${cacheKey}') format('woff2');`,
        `    unicode-range: ${range.trim()};`,
        '}',
        BLOCK_END,
    ].join('\n');
}

/** The text between the markers, markers included, or null when the sheet has none. */
export function findFontFaceBlock(css) {
    const start = css.indexOf(BLOCK_BEGIN);
    const end = css.indexOf(BLOCK_END);
    return start === -1 || end === -1 || end < start ? null : css.slice(start, end + BLOCK_END.length);
}

/** Replaces the block, or on the first run puts it after the opening comment of the sheet. */
export function placeFontFaceBlock(css, block) {
    const current = findFontFaceBlock(css);
    if (current !== null) {
        return css.replace(current, () => block);
    }
    const afterOpeningComment = css.indexOf('*/\n') + '*/\n'.length;
    return `${css.slice(0, afterOpeningComment)}${block}\n${css.slice(afterOpeningComment)}`;
}
